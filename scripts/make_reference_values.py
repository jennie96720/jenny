"""Generate docs/reference_values.md: numbers to check an independent (e.g. Fortran) implementation
step by step against this Python code.  Grid-dependent numbers are given together with the exact
quadrature definition (qdq/quadrature.py) so they can be reproduced digit by digit."""
import sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import numpy as np
from qdq.quark import sigmas, mass_function
from qdq.diquark import coupling
from qdq.faddeev import NucleonFaddeev, flavour_coeffs
from qdq.quadrature import radial, chebyshev_u
from scipy.optimize import brentq

L = []
w = L.append
w("# Reference values for an independent implementation\n")
w("Generated by `scripts/make_reference_values.py`. Units: GeV. Euclidean metric, P = (0,0,0,iM).\n")
w("## Step 1 — dressed-quark propagator  S(p) = -i γ·p σ_V + σ_S\n")
w("| p² | σ_V(p²) [GeV⁻²] | σ_S(p²) [GeV⁻¹] | M(p²) = σ_S/σ_V |\n|---|---|---|---|")
for p2 in [0.0, 0.1, 1.0, -0.1 + 0.2j, -0.25 + 0.5j]:
    sv, ss = sigmas(np.array([p2]))
    m = mass_function(np.array([p2]))
    w(f"| {p2} | {complex(sv[0]):.12g} | {complex(ss[0]):.12g} | {complex(m[0]):.12g} |")
ME = brentq(lambda p: p**2 - mass_function(p**2).real**2, 0.05, 2.0)
w(f"\nEuclidean constituent mass (p² = M²(p²)): M^E = {ME:.10f} GeV;  m_q = {0.00897 * 0.566 * 1e3:.4f} MeV\n")

w("## Step 2 — diquark canonical normalisation (colour trace 2, unit-norm flavour matrices)\n")
for ch in ['0+', '1+']:
    g, g2, cf = coupling(ch, nq=200, nz=24)
    w(f"- {ch}: g² = {g2.real:.6f}  →  g = {complex(g):.6f}   (2611.19819 quotes 2×|g|: {2 * abs(g):.4f})")
w("\nWith Γ⁰⁺ = g C iγ₅ F, Γ¹⁺_μ = g iγ_μ C F, Γ̄ = C† Γᵀ C, C = γ₂γ₄ and our γ representation, "
  "g₁₊² < 0: keep g₁₊ = +i|g₁₊|.\n")

w("## Step 3 — flavour coefficients of the Faddeev kernel (proton)\n")
c = flavour_coeffs()
w("| c_ss | c_sa | c_as | c_aa |\n|---|---|---|---|")
w(f"| {c['ss']:.10f} | {c['sa']:.10f} | {c['as']:.10f} | {c['aa']:.10f} |\n")

w("## Step 4 — Faddeev eigenvalue λ(M) (exact grids, Nyström, couplings 14.94/2 and 12.98 i/2)\n")
r, wr = radial(4, 0.6)
w("Quadrature (qdq/quadrature.py): radial = Gauss–Legendre t∈(0,1), |ℓ| = s·t/(1−t), weight s/(1−t)², s = 0.6;")
w("z = cos of 4-angle: Gauss–Chebyshev 2nd kind, z_k = cos(kπ/(n+1)), w_k = π/(n+1) sin²(kπ/(n+1));")
w("y = cos of 3-angle between k and ℓ: Gauss–Legendre; azimuth: factor 2π; measure ∫d⁴ℓ/(2π)⁴.")
w(f"(e.g. 4 radial nodes: |ℓ| = {np.array2string(r, precision=10)})\n")
w("| grid (n_r, n_z, n_y) | channels | M | λ_max |\n|---|---|---|---|")
for npts in [(8, 4, 4), (16, 8, 8)]:
    for ch in ['s', 'sa']:
        F = NucleonFaddeev(g=(14.94 / 2, 1j * 12.98 / 2), nr=npts[0], nz=npts[1], ny=npts[2], ncheb=None, channels=ch)
        for M in [1.10, 1.18]:
            lam = F.eigen(M)[0]
            w(f"| {npts} | {ch} | {M} | {lam.real:.10f} |")
w("\nConverged masses: full M_N = 1.1787 GeV (paper g/2) / 1.1742 GeV (own g); scalar diquark only 1.4593 / 1.4554 GeV.\n")

w("## Steps 5–6 — currents (normalised, grid-converged to the digits shown)\n")
w("""- Normalisation from the eigenvalue: impulse (diagrams 1+2, baryon charges) share of the baryon number = 0.8026.
- F₁(0) by diagram, proton: 0.4719, 0.3449, 0, 0.152, 0.0155, 0.0155 → 1.000; neutron: −0.0638, 0.0496, 0, 0.045, −0.0155, −0.0155 → 0.000.
- u-number current: 2.001, d-number: 1.001 (coarse two-loop grid).
- EM static: μ_p = 2.71, μ_n = −1.78, r_E^p = 0.68 fm, r_E^n² = −0.088 fm², r_M^p = 0.64 fm, r_M^n = 0.69 fm.
- Gravitational, Q = 0: A = 1.004 [diagrams 0.518, 0.310, 0, 0.090, 0.043, 0.043], A^s/A^a/A^m = 0.535/0.339/0.130, A^u/A^d = 0.689/0.314.
- Gravitational, Q² = 0.695 GeV²: A = 0.5595, J = 0.266, D = −0.805.
""")
pathlib.Path('docs').mkdir(exist_ok=True)
open('docs/reference_values.md', 'w').write("\n".join(L) + "\n")
print("\n".join(L))
